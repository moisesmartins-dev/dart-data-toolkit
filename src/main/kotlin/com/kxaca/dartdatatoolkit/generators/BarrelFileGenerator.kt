package com.kxaca.dartdatatoolkit.generators

import java.io.File

data class BarrelFile(
    val path: String,
    val exports: List<String>,
    val withComments: Boolean = false
)

class BarrelFileAnalyzer {

    fun findDartFiles(
        directory: File,
        recursive: Boolean = true,
        excludeIndex: Boolean = true
    ): List<File> {
        val dartFiles = mutableListOf<File>()

        if (!directory.exists() || !directory.isDirectory) return dartFiles

        directory.listFiles()?.forEach { file ->
            when {
                file.isFile && file.name.endsWith(".dart") -> {
                    if (!excludeIndex || !isIndexFile(file.name)) dartFiles.add(file)
                }
                file.isDirectory && recursive -> {
                    if (!isSpecialDirectory(file.name)) {
                        dartFiles.addAll(findDartFiles(file, recursive, excludeIndex))
                    }
                }
            }
        }

        return dartFiles.sortedBy { it.name }
    }

    fun extractExportables(file: File): List<String> {
        val content = file.readText()
        val exports = mutableListOf<String>()

        val patterns = listOf(
            Regex("""(?:class|enum|mixin)\s+(\w+)"""),
            Regex("""(?:const\s+)?(?:final\s+)?(\w+)\s*\("""),
            Regex("""(?:Future|Stream)<(\w+)>\s+(\w+)\s*\(""")
        )

        patterns.forEach { pattern ->
            pattern.findAll(content).forEach { match ->
                val name = match.groupValues[1]
                if (name.isNotEmpty() && !exports.contains(name)) exports.add(name)
            }
        }

        return exports
    }

    private fun isIndexFile(filename: String): Boolean =
        listOf("index.dart", "lib_all.dart", "barrel.dart").contains(filename.lowercase())

    private fun isSpecialDirectory(dirname: String): Boolean =
        listOf(".dart_tool", "build", ".git", "node_modules", ".idea", "pubspec", ".pub", ".packages")
            .contains(dirname.lowercase())
}

class BarrelFileGenerator {

    fun generateBarrel(
        files: List<File>,
        baseDirectory: File,
        withFileComments: Boolean = false
    ): String {
        if (files.isEmpty()) return generateHeader()

        val lines = mutableListOf(generateHeader())

        files.sortedBy { it.name }.forEach { file ->
            val relativePath = file.relativeTo(baseDirectory).path.replace("\\", "/")
            if (withFileComments) {
                lines.add("")
                lines.add("// ${file.name}")
            }
            lines.add("export '$relativePath';")
        }

        return lines.joinToString("\n")
    }

    fun generateOrganizedBarrel(
        filesByCategory: Map<String, List<File>>,
        baseDirectory: File
    ): String {
        if (filesByCategory.isEmpty()) return generateHeader()

        val lines = mutableListOf(generateHeader())

        filesByCategory.forEach { (category, files) ->
            lines.add("")
            lines.add("// $category")
            files.sortedBy { it.name }.forEach { file ->
                val relativePath = file.relativeTo(baseDirectory).path.replace("\\", "/")
                lines.add("export '$relativePath';")
            }
        }

        return lines.joinToString("\n")
    }

    fun generateBarrelWithDocs(
        files: List<File>,
        baseDirectory: File,
        analyzer: BarrelFileAnalyzer = BarrelFileAnalyzer()
    ): String {
        if (files.isEmpty()) return generateHeader()

        val lines = mutableListOf(generateHeader())

        files.sortedBy { it.name }.forEach { file ->
            val relativePath = file.relativeTo(baseDirectory).path.replace("\\", "/")
            val exportables = analyzer.extractExportables(file)
            lines.add("")
            lines.add("// ${file.name}")
            if (exportables.isNotEmpty()) lines.add("// Exports: ${exportables.joinToString(", ")}")
            lines.add("export '$relativePath';")
        }

        return lines.joinToString("\n")
    }

    private fun generateHeader(): String =
        "/// This file is a barrel file. It exports all public APIs from this package.\n" +
        "/// Generated by Dart Data Class Generator"
}
